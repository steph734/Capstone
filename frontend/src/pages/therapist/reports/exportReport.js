import { anonymizer } from './config.jsx'

const PCT = new Set(['progress', 'accuracy', 'rate'])
export function fmtCell(key, v) {
  if (v == null || v === '') return '—'
  if (PCT.has(key)) return `${v}%`
  if (key === 'change') return `${v > 0 ? '+' : ''}${v} pts`
  if (key === 'revenue') return `PHP ${Number(v).toLocaleString('en-PH')}`
  if (key === 'avgDuration') return `${v} min`
  return String(v)
}
export const fmtKpi = (k) => `${k.decimals ? Number(k.value).toFixed(1) : k.value}${k.suffix || ''}`
export const changeText = (k) => (k.changePct == null ? (k.value > 0 && k.previous === 0 ? 'new' : '–') : `${k.changePct > 0 ? '+' : ''}${k.changePct}%`)

async function logoData() {
  try {
    const res = await fetch('/therapy-pro-logo.png')
    if (!res.ok) return null
    const blob = await res.blob()
    return await new Promise((r) => { const fr = new FileReader(); fr.onload = () => r(fr.result); fr.readAsDataURL(blob) })
  } catch { return null }
}

// Applies "Patient A, B, ..." to every patient name in the rows (same mapping for charts and tables).
export function withAnonymity(rows, anonymize) {
  if (!anonymize) return { rows, mapName: undefined }
  const mapName = anonymizer()
  return { rows: rows.map((r) => (r.patient ? { ...r, patient: mapName(r.patient) } : r)), mapName }
}

function header(doc, { logo, title, filtersText, therapist, range }) {
  if (logo) doc.addImage(logo, 'PNG', 14, 10, 16, 16)
  doc.setFontSize(16); doc.setTextColor(44, 74, 62); doc.text('TherapyPro', logo ? 33 : 14, 17)
  doc.setFontSize(10); doc.setTextColor(100); doc.text('Therapy clinic', logo ? 33 : 14, 23)
  doc.setFontSize(18); doc.setTextColor(26, 58, 48); doc.text(title, 14, 36)
  doc.setFontSize(10); doc.setTextColor(90)
  doc.text(`Period: ${range.from} to ${range.to}`, 14, 43)
  doc.text(`Filters: ${filtersText}`, 14, 49)
  doc.text(`Generated by ${therapist} on ${new Date().toLocaleDateString('en-PH', { year: 'numeric', month: 'long', day: 'numeric' })}`, 14, 55)
}

function pageNumbers(doc) {
  const n = doc.getNumberOfPages()
  for (let i = 1; i <= n; i += 1) {
    doc.setPage(i); doc.setFontSize(9); doc.setTextColor(130)
    doc.text(`Page ${i} of ${n}`, doc.internal.pageSize.getWidth() - 14, doc.internal.pageSize.getHeight() - 8, { align: 'right' })
  }
}

// The report PDF: clinic name + logo, report name, range, filters, "Generated by", KPIs, charts as images, table, page numbers.
export async function buildReportPdf({ title, range, filtersText, therapist, kpis, charts, extra = [], cols, rows, anonymize }) {
  const doc = new jsPDF({ orientation: 'landscape' })
  const logo = await logoData()
  const { rows: rr, mapName } = withAnonymity(rows, anonymize)
  header(doc, { logo, title, filtersText: anonymize ? `${filtersText} · names anonymised` : filtersText, therapist, range })

  let y = 62
  const w = (doc.internal.pageSize.getWidth() - 28 - (kpis.length - 1) * 4) / kpis.length
  kpis.forEach((k, i) => {
    const x = 14 + i * (w + 4)
    doc.setFillColor(243, 249, 246); doc.roundedRect(x, y, w, 20, 2, 2, 'F')
    doc.setFontSize(15); doc.setTextColor(21, 154, 114); doc.text(fmtKpi(k), x + 4, y + 9)
    doc.setFontSize(8); doc.setTextColor(90); doc.text(k.label, x + 4, y + 14)
    doc.setTextColor(k.changePct == null ? 120 : (k.changePct >= 0) === (k.good === 'up') ? 22 : 220, k.changePct == null ? 120 : (k.changePct >= 0) === (k.good === 'up') ? 163 : 38, k.changePct == null ? 120 : (k.changePct >= 0) === (k.good === 'up') ? 74 : 38)
    doc.text(`${changeText(k)} vs previous period`, x + 4, y + 18)
  })
  y += 26

  const imgs = await Promise.all([charts.primary, charts.secondary].filter(Boolean).map(async (c) => ({ c, img: await chartToImage(c, mapName) })))
  const cw = (doc.internal.pageSize.getWidth() - 28 - 6) / 2
  imgs.forEach(({ c, img }, i) => {
    const x = 14 + i * (cw + 6)
    doc.setFontSize(10); doc.setTextColor(44, 74, 62); doc.text(c.title, x, y + 4)
    if (img) doc.addImage(img, 'PNG', x, y + 6, cw, cw / 2)
  })
  y += 6 + cw / 2 + 6
  extra.filter(Boolean).forEach((line) => { doc.setFontSize(9); doc.setTextColor(90); const t = doc.splitTextToSize(line, doc.internal.pageSize.getWidth() - 28); doc.text(t, 14, y); y += t.length * 4.5 })

  autoTable(doc, {
    head: [cols.map(([, l]) => l)], body: rr.map((r) => cols.map(([k]) => fmtCell(k, r[k]))), startY: y + 2,
    styles: { fontSize: 9, cellPadding: 3 }, headStyles: { fillColor: [74, 107, 93], textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [245, 250, 248] }, margin: { left: 14, right: 14 },
  })
  pageNumbers(doc)
  return doc
}

export function buildReportExcel({ title, range, filtersText, therapist, kpis, cols, rows, anonymize }) {
  const { rows: rr } = withAnonymity(rows, anonymize)
  const wb = XLSX.utils.book_new()
  const t = XLSX.utils.aoa_to_sheet([cols.map(([, l]) => l), ...rr.map((r) => cols.map(([k]) => (PCT.has(k) || k === 'revenue' || typeof r[k] === 'number' ? r[k] ?? '' : fmtCell(k, r[k]))))])
  t['!cols'] = cols.map(() => ({ wch: 20 }))
  XLSX.utils.book_append_sheet(wb, t, 'Table')
  const k = XLSX.utils.aoa_to_sheet([
    [title], [`Period: ${range.from} to ${range.to}`], [`Filters: ${filtersText}${anonymize ? ' · names anonymised' : ''}`], [`Generated by ${therapist} on ${new Date().toLocaleDateString('en-PH')}`], [],
    ['KPI', 'Value', 'Previous period', 'Change %'], ...kpis.map((x) => [x.label, x.value, x.previous ?? '', x.changePct ?? '']),
  ])
  k['!cols'] = [{ wch: 28 }, { wch: 14 }, { wch: 18 }, { wch: 12 }]
  XLSX.utils.book_append_sheet(wb, k, 'KPI summary')
  return wb
}

// The individual patient report, written for parents: letterhead, plain-language summary, signature line.
export async function buildPatientPdf({ data, range, therapist, anonymize }) {
  const doc = new jsPDF({ orientation: 'portrait' })
  const logo = await logoData()
  const mapName = anonymize ? anonymizer() : null
  const name = mapName ? mapName(data.header.name) : data.header.name
  if (logo) doc.addImage(logo, 'PNG', 14, 10, 18, 18)
  doc.setFontSize(18); doc.setTextColor(44, 74, 62); doc.text('TherapyPro', logo ? 36 : 14, 18)
  doc.setFontSize(10); doc.setTextColor(100); doc.text('Progress report for parents and guardians', logo ? 36 : 14, 25)
  doc.setDrawColor(200); doc.line(14, 32, 196, 32)
  doc.setFontSize(15); doc.setTextColor(26, 58, 48); doc.text(name, 14, 42)
  doc.setFontSize(10); doc.setTextColor(90)
  doc.text(`Age: ${data.header.age ?? '—'}   Condition: ${data.header.condition}   Guardian: ${anonymize ? '—' : data.header.guardian}`, 14, 49)
  doc.text(`Therapist: ${data.header.therapist}   Period: ${range.from} to ${range.to}`, 14, 55)
  let y = 64
  const para = (title, text) => {
    if (!text) return
    doc.setFontSize(11); doc.setTextColor(44, 74, 62); doc.text(title, 14, y); y += 5
    doc.setFontSize(10); doc.setTextColor(60); const l = doc.splitTextToSize(text, 182); doc.text(l, 14, y); y += l.length * 5 + 4
    if (y > 260) { doc.addPage(); y = 20 }
  }
  para('Summary', data.summary)
  autoTable(doc, { head: [['Measure', 'Now', 'Before', 'Change']], body: data.kpis.map((k) => [k.label, fmtKpi(k), k.previous == null ? '—' : `${k.previous}${k.suffix || ''}`, changeText(k)]), startY: y, styles: { fontSize: 10 }, headStyles: { fillColor: [74, 107, 93] }, margin: { left: 14, right: 14 } })
  y = doc.lastAutoTable.finalY + 8
  const imgs = await Promise.all([data.charts.primary, data.charts.secondary].map((c) => chartToImage(c, null)))
  imgs.forEach((img, i) => { if (img) { if (y > 215) { doc.addPage(); y = 20 } doc.setFontSize(10); doc.setTextColor(44, 74, 62); doc.text([data.charts.primary, data.charts.secondary][i].title, 14, y); doc.addImage(img, 'PNG', 14, y + 2, 120, 60); y += 68 } })
  para('Latest assessment', data.sections.soap?.assessment)
  para('Plan', data.sections.soap?.plan)
  if (data.sections.exercises.length) {
    autoTable(doc, { head: [['Home exercise', 'Status']], body: data.sections.exercises.map((e) => [e.name, e.status]), startY: y, styles: { fontSize: 10 }, headStyles: { fillColor: [74, 107, 93] }, margin: { left: 14, right: 14 } })
    y = doc.lastAutoTable.finalY + 8
  }
  para('Games', data.sections.games.played ? `${data.sections.games.played} games played${data.sections.games.favorite ? `, favourite: ${data.sections.games.favorite}` : ''}${data.sections.games.badges.length ? `. Badges: ${data.sections.games.badges.join(', ')}` : ''}.` : '')
  para('Therapist remarks', data.sections.remarks.text)
  if (y > 250) { doc.addPage(); y = 30 }
  doc.setTextColor(60); doc.setFontSize(11)
  doc.text('Therapist: ______________________________      Date: ______________', 14, Math.max(y + 12, 262))
  pageNumbers(doc)
  return doc
}
